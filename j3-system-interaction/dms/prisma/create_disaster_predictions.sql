CREATE TABLE IF NOT EXISTS disaster_predictions (
    prediction_id          SERIAL PRIMARY KEY,
    division_id            INTEGER NOT NULL REFERENCES "Division"(division_id) ON DELETE CASCADE,
    feature_date           DATE NOT NULL,
    predicted_for_date     DATE NOT NULL,
    horizon                INTEGER NOT NULL CHECK (horizon IN (1, 2, 3)),
    hazard_type            VARCHAR(20) NOT NULL CHECK (hazard_type IN ('FLOOD', 'LANDSLIDE', 'DROUGHT')),
    prob_normal            DOUBLE PRECISION,
    prob_moderate          DOUBLE PRECISION,
    prob_severe            DOUBLE PRECISION,
    prob_extreme           DOUBLE PRECISION,
    predicted_severity     INTEGER CHECK (predicted_severity BETWEEN 0 AND 3),
    predicted_severity_label VARCHAR(10),
    run_at                 TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_disaster_predictions
        UNIQUE (division_id, feature_date, hazard_type, horizon)
);

CREATE INDEX IF NOT EXISTS idx_disaster_predictions_division_date
    ON disaster_predictions (division_id, feature_date);

CREATE INDEX IF NOT EXISTS idx_disaster_predictions_hazard_date
    ON disaster_predictions (hazard_type, predicted_for_date);

COMMENT ON TABLE disaster_predictions IS
    'Probabilistic disaster severity predictions (Day+1/+2/+3) generated by the Flood, Landslide, and Drought ensemble models.';

COMMENT ON COLUMN disaster_predictions.feature_date IS
    'The date of the forecast_features row used as model input.';

COMMENT ON COLUMN disaster_predictions.predicted_for_date IS
    'The calendar date being predicted (= feature_date + horizon days).';

COMMENT ON COLUMN disaster_predictions.horizon IS
    'Forecast horizon: 1 = tomorrow, 2 = day after tomorrow, 3 = three days out.';

COMMENT ON COLUMN disaster_predictions.hazard_type IS
    'Which disaster model produced this row: FLOOD, LANDSLIDE, or DROUGHT.';

COMMENT ON COLUMN disaster_predictions.prob_normal IS
    'Probability of Normal severity (class 0). All four prob_* columns sum to ~1.0.';

COMMENT ON COLUMN disaster_predictions.predicted_severity IS
    'argmax of the four probability columns: 0=Normal, 1=Moderate, 2=Severe, 3=Extreme.';
